"""
This module defines classes used to track and serialize game move history.
It stores past moves and future moves to support undo/redo workflows.
"""

from carcassonne.Datas.Serializer import build_str


class MoveRecord:
    """Store metadata for a single move in history."""

    def __init__(self, move_str: str, player_id: int = 1, is_ai: bool = False) -> None:
        """
        Initialize a move history record.

        Args:
            move_str: Raw move command as entered/executed
            player_id: Identifier of the player who made the move
            is_ai: Whether the move was generated by the AI
        """
        self.move_str: str = move_str
        self.player_id: int = player_id
        self.is_ai_move: bool = is_ai


class History:
    """Manage move history stacks for undo/redo operations."""

    def __init__(self) -> None:
        """Initialize empty stacks for past and future moves."""
        self.past_moves: list[MoveRecord] = []
        self.future_moves: list[MoveRecord] = []

    def push_past(self, record: MoveRecord) -> None:
        """Push a move record into the past stack."""
        self.past_moves.append(record)

    def push_future(self, record: MoveRecord) -> None:
        """Push a move record into the future stack (redo stack)."""
        self.future_moves.append(record)

    def pop_past(self) -> MoveRecord:
        """Pop and return the latest move from the past stack."""
        return self.past_moves.pop()

    def pop_future(self) -> MoveRecord:
        """Pop and return the latest move from the future stack."""
        return self.future_moves.pop()

    def clear_future(self) -> None:
        """Clear redo history after a new move is committed."""
        self.future_moves.clear()

    def clear_history(self) -> None:
        """Clear all stored history, both past and future."""
        self.past_moves.clear()
        self.future_moves.clear()

    def list_history(self) -> list[str]:
        """
        Return serialized move history.

        Returns:
            List of printable move strings for past moves
        """
        return [build_str(record) for record in self.past_moves]
